  /// All baked corridors with the stop ids that anchor each end.
  static const Map<String, List<String>> corridorEndStopIds = {
    'vit-main-gate|katpadi-railway-station': ['vit-main-gate', 'katpadi-railway-station'],
    'vit-main-gate|old-bus-stand': ['vit-main-gate', 'old-bus-stand'],
    'old-bus-stand|katpadi-railway-station': ['old-bus-stand', 'katpadi-railway-station'],
  };

  /// Returns the baked road path for a pair of endpoint stop ids in either
  /// direction, or `null` when the pair has no baked corridor.
  static List<LatLng>? pathForEndpoints(String stopIdA, String stopIdB) {
    final forward = corridorEndStopIds['${stopIdA}|${stopIdB}'];
    if (forward != null) return _pathForCorridor(forward);
    final reverse = corridorEndStopIds['${stopIdB}|${stopIdA}'];
    if (reverse != null) return _pathForCorridor(reverse).reversed.toList();
    return null;
  }

  static List<LatLng> _pathForCorridor(List<String> endpoints) {
    if (endpoints[0] == 'vit-main-gate' && endpoints[1] == 'katpadi-railway-station') {
      return _vitToKatpadi;
    }
    if (endpoints[0] == 'vit-main-gate' && endpoints[1] == 'old-bus-stand') {
      return _vitToOldBusStand;
    }
    return _oldBusStandToKatpadi;
  }
